"""Leaderboard: results/*.json (practice sessions) -> LEADERBOARD.md, plus grand prix standings.

    python -m agentic_gp.race.leaderboard                       # writes LEADERBOARD.md
    python -m agentic_gp.race.leaderboard --results results --out LEADERBOARD.md --baseline Max
    python -m agentic_gp.race.leaderboard --track sprint      # one track only

    from agentic_gp.race.leaderboard import standings_markdown, championship, championship_markdown
    print(standings_markdown(gp_result))                        # race classification table
    rows = championship([home_gp, mystery_gp])                  # points over several grand prix

A result file is what `SessionResult.to_result_dict()` writes (`python race.py drive X.py --save`
-> results/<driver>_<track>.json). Lap times are only comparable on the same track, so the board has
one table per track. Ranking: best lap (sim time + penalties of the lap), ties -> fewer crashes;
drivers without a finished lap come after, ordered by how far they got.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

DEFAULT_BASELINE = "Max"        # the house racer
DNF_POINT_GATES = 8             # a DNF that passed this many gates still scores 1 point


def load_results(results_dir: str | Path = "results") -> list[dict]:
    """Every readable result JSON in the folder (bad files are skipped)."""
    out = []
    for p in sorted(Path(results_dir).glob("*.json")):
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError, OSError):
            continue
        if not isinstance(data, dict) or "name" not in data:
            continue
        data["_file"] = p.name
        out.append(data)
    return out


def sort_key(r: dict) -> tuple:
    best = r.get("best_lap")
    if best is None:
        return (1, -int(r.get("max_waypoints_passed", 0)), int(r.get("total_crashes", 0)))
    return (0, float(best), int(r.get("total_crashes", 0)))


def _attempts(r: dict) -> tuple[int, int]:
    atts = r.get("attempts", []) or []
    return len(atts), sum(1 for a in atts if a.get("completed"))


def _llm_calls(r: dict) -> int | None:
    if "llm_calls" in r:
        return int(r["llm_calls"])
    llm = r.get("llm") or {}
    return int(llm["calls"]) if "calls" in llm else None


def render_markdown(results: list[dict], baseline_name: str = DEFAULT_BASELINE, track: str | None = None) -> str:
    """The practice leaderboard as markdown: one table per track (lap times of different tracks are not
    comparable), the most popular track first; `track` keeps only that one. Baseline = the house racer."""
    if track is not None:
        results = [r for r in results if str(r.get("track", "-")) == track]
    groups: dict[str, list[dict]] = {}
    for r in results:
        groups.setdefault(str(r.get("track", "-")), []).append(r)
    order = sorted(groups, key=lambda k: (-len(groups[k]), k))
    lines = [
        "# Agentic Grand Prix - Leaderboard",
        "",
        "Best lap = simulated time + 5 s per crash (+ zone penalties). Lower is better. "
        "DNF = no finished lap. One table per track.",
    ]
    for key in order or [track or "-"]:
        if len(order) > 1:
            lines += ["", f"## {key}"]
        lines += [""] + _table(groups.get(key, []), baseline_name)
    lines += ["", f"_{len(results)} entries. Generated by `python -m agentic_gp.race.leaderboard`._"]
    return "\n".join(lines) + "\n"


def _table(results: list[dict], baseline_name: str) -> list[str]:
    results = sorted(results, key=sort_key)
    base = next((r for r in results if str(r.get("name", "")).lower() == baseline_name.lower()), None)
    base_lap = base.get("best_lap") if base else None
    lines = [
        f"| # | Driver | Kind | Track | Best lap (s) | vs {baseline_name} | Attempts (finished) | Crashes "
        "| Max WP | LLM calls | Model | Submitted |",
        "|---|--------|------|-------|-------------:|------:|--------------------:|--------:|-------:|----------:"
        "|-------|-----------|",
    ]
    for i, r in enumerate(results, 1):
        best = r.get("best_lap")
        best_s = f"{best:.2f}" if best is not None else "DNF"
        if base_lap is not None and best is not None:
            vs = f"{best - base_lap:+.2f}"
        elif base is not None and base_lap is None and best is not None:
            vs = "beats DNF"
        else:
            vs = "-"
        n_att, n_fin = _attempts(r)
        name = str(r.get("name", r.get("_file", "?")))
        if base is r:
            name = f"**{name}** (house)"
        calls = _llm_calls(r)
        lines.append(
            f"| {i} | {name} | {r.get('kind', '-')} | {r.get('track', '-')} | {best_s} | {vs} | {n_att} ({n_fin}) "
            f"| {r.get('total_crashes', 0)} | {r.get('max_waypoints_passed', 0)} | "
            f"{'-' if calls is None else calls} | {r.get('model') or '-'} | {str(r.get('timestamp', ''))[:19]} |"
        )
    if not results:
        lines.append("| - | *(no results yet)* | | | | | | | | | | |")
    return lines


# ---------------------------------------------------------------------------- grand prix
def _gp_dict(gp: Any) -> dict:
    return gp if isinstance(gp, dict) else gp.to_dict()


def standings_markdown(gp_result: Any) -> str:
    """Race classification of a GrandPrixResult (or its to_dict()) as markdown."""
    d = _gp_dict(gp_result)
    lines = [f"# {d.get('title', 'Grand Prix')} - {d.get('track_name', d.get('track', ''))}", "",
             "| Pos | Driver | Kind | Grid | Race time | Gap | Laps | Best lap | Crashes | LLM calls | Status |",
             "|----:|--------|------|-----:|----------:|----:|-----:|---------:|--------:|----------:|--------|"]
    for r in d.get("standings", []):
        rt = f"{r['race_time']:.2f}" if r.get("race_time") is not None else "-"
        best = f"{r['best_lap']:.2f}" if r.get("best_lap") is not None else "-"
        name = r["name"] + (" (house)" if r.get("house") else "")
        lines.append(f"| {r['position']} | {name} | {r.get('kind', '-')} | {r.get('grid') or '-'} | {rt} | "
                     f"{r.get('gap_text', '')} | {r.get('laps_completed', 0)} | {best} | {r.get('crashes', 0)} | "
                     f"{r.get('llm_calls', 0)} | {r.get('status') or 'finished'} |")
    if d.get("qualifying"):
        pole = d["qualifying"][0]
        if pole.get("qualifying_time") is not None:
            lines += ["", f"Pole position: **{pole['name']}** ({pole['qualifying_time']:.2f} s)."]
    return "\n".join(lines) + "\n"


def championship(gp_results: list[Any]) -> list[dict]:
    """Points over several grand prix (A13): N+1-position for finishers (N = scored cars in that race),
    1 point for a DNF that passed >= 8 gates, 0 otherwise. House cars race but are not scored and do not
    take positions away. Ties: better result in the LAST race (the mystery track), then name."""
    table: dict[str, dict] = {}
    races = [_gp_dict(g) for g in gp_results]
    for ri, d in enumerate(races):
        scored = [r for r in d.get("standings", []) if not r.get("house")]
        n = len(scored)
        for pos, r in enumerate(scored, 1):
            finished = r.get("race_time") is not None and not r.get("status")
            pts = n + 1 - pos if finished else (1 if int(r.get("waypoints_passed", 0)) >= DNF_POINT_GATES else 0)
            row = table.setdefault(r["name"], {"name": r["name"], "author": r.get("author"), "kind": r.get("kind"),
                                               "points": 0, "results": [None] * len(races)})
            row["points"] += pts
            row["results"][ri] = {"position": pos, "points": pts, "race_time": r.get("race_time"),
                                  "status": r.get("status", "")}
    last = len(races) - 1

    def key(row: dict) -> tuple:
        lr = row["results"][last] if last >= 0 else None
        return (-row["points"], lr["position"] if lr else 10**6, row["name"])

    rows = sorted(table.values(), key=key)
    for i, row in enumerate(rows, 1):
        row["position"] = i
    return rows


def championship_markdown(rows: list[dict], titles: list[str] | None = None) -> str:
    n = max((len(r["results"]) for r in rows), default=0)
    titles = titles or [f"Race {i + 1}" for i in range(n)]
    lines = ["# Championship", "",
             "| Pos | Driver | Points | " + " | ".join(titles) + " |",
             "|----:|--------|-------:|" + "|".join(["---:"] * n) + "|"]
    for r in rows:
        cells = []
        for res in r["results"]:
            cells.append("-" if res is None else f"P{res['position']} ({res['points']})")
        lines.append(f"| {r['position']} | {r['name']} | {r['points']} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", "--results-dir", dest="results", default="results")
    ap.add_argument("--out", default="LEADERBOARD.md")
    ap.add_argument("--baseline", default=DEFAULT_BASELINE)
    ap.add_argument("--track", default=None, help="only this track (default: one table per track)")
    args = ap.parse_args(argv)
    md = render_markdown(load_results(args.results), baseline_name=args.baseline, track=args.track)
    Path(args.out).write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
